"""The machine a profile is: one Phasmid profile JSON, generated once and kept.

A Phasmid profile (``profiles/schema.json`` in the Phasmid repository) describes
one device: OS, GPU, screen, fonts, CPU and memory, voices, media devices, and a
seed for every deterministic perturbation. It is generated by Phasmid's own
``genprofile`` from captured real-device data, so every combination exists in
the wild, and it is stored on the profile as ``Profile.fingerprint``.

Not all of it is the machine. The location group (``locale``: timezone,
languages, geolocation; ``network.webrtc.public_ip``) describes where the
machine connects from and must follow the proxy: Phasmid's schema requires the
WebRTC address to equal the exit IP, and a Berlin clock behind a Tokyo exit is a
contradiction any page can measure. So a launch looks up the exit address and,
when it moved, regenerates the profile from the same seed and *takes only the
location group* from the result. The hardware is copied from the stored pin
rather than trusted to regenerate identically: a newer genprofile may sample
differently, and a warmed-up account must not get new hardware because the
generator was updated.
"""

from __future__ import annotations

import asyncio
import copy
import os
import secrets
from functools import lru_cache
from pathlib import Path
from typing import Any, cast

from loguru import logger

from . import browser_install
from .browser_install import GenprofileError
from .models import BrowserSettings, OsFamily

OS_FAMILIES = ("linux", "windows")


class MachineError(ValueError):
    """A machine could not be generated or moved; the message says why."""


def new_seed() -> str:
    """A fresh 128-bit seed: a different machine."""
    return secrets.token_hex(16)


def host_timezone() -> str:
    """This computer's IANA zone, for a profile generated with no network.

    Only a fallback: a launch moves the profile to its exit address anyway.
    """
    zone = os.environ.get("TZ", "").lstrip(":")
    if zone and "/" in zone:
        return zone
    try:
        target = os.path.realpath("/etc/localtime")
        marker = "/zoneinfo/"
        if marker in target:
            return target.split(marker, 1)[1]
    except OSError:
        pass
    try:
        return Path("/etc/timezone").read_text().strip() or "UTC"
    except OSError:
        return "UTC"


def pinned_os(pin: dict[str, Any] | None) -> OsFamily | None:
    """The OS a pinned machine claims, which can differ from the profile's setting."""
    if not pin:
        return None
    family = (pin.get("os") or {}).get("family")
    return cast(OsFamily, family) if family in OS_FAMILIES else None


def pinned_gpu(pin: dict[str, Any] | None) -> str | None:
    gpu = (pin or {}).get("gpu") or {}
    if gpu.get("vendor_id") and gpu.get("device_id"):
        return f"{gpu['vendor_id']}:{gpu['device_id']}"
    return None


def pinned_location(pin: dict[str, Any] | None) -> dict[str, Any]:
    """Where the pin says the machine is: exit address, zone and languages."""
    locale = (pin or {}).get("locale") or {}
    webrtc = ((pin or {}).get("network") or {}).get("webrtc") or {}
    return {
        "public_ip": webrtc.get("public_ip"),
        "timezone": locale.get("timezone"),
        "languages": locale.get("languages"),
        "geolocation": locale.get("geolocation"),
    }


def _request(
    os_family: str, seed: str, settings: BrowserSettings, exit_ip: str | None, gpu: str | None
) -> dict[str, Any]:
    args: dict[str, Any] = {"os": os_family, "seed": seed}
    if gpu:
        args["gpu"] = gpu
    if settings.languages:
        args["languages"] = settings.languages
    # A stated timezone wins over the exit's location: it is the user's
    # decision, and the proxy check reports when it contradicts the exit.
    if settings.timezone:
        args["timezone"] = settings.timezone
    elif exit_ip:
        args["exit_ip"] = exit_ip
    else:
        args["timezone"] = host_timezone()
    return args


async def _generate(args: dict[str, Any]) -> dict[str, Any]:
    try:
        answer = await asyncio.to_thread(browser_install.run_genprofile, "generate", args)
    except GenprofileError as exc:
        raise MachineError(f"Could not generate a machine: {exc}") from exc
    return answer["profile"]


async def _generate_at(
    os_family: str, seed: str, settings: BrowserSettings, exit_ip: str | None, gpu: str | None
) -> dict[str, Any]:
    pin = await _generate(_request(os_family, seed, settings, exit_ip, gpu))
    if settings.timezone and exit_ip:
        # A stated zone replaces the exit's location, not its address: WebRTC's
        # UDP does not go through the proxy, and Phasmid answers the srflx
        # candidate with this address instead of the host's real one.
        pin.setdefault("network", {}).setdefault("webrtc", {})["public_ip"] = exit_ip
    return pin


async def generate(
    settings: BrowserSettings, exit_ip: str | None = None, seed: str | None = None
) -> dict[str, Any]:
    """A new machine for these settings, placed at ``exit_ip`` when one is known."""
    seed = seed or new_seed()
    pin = await _generate_at(settings.os, seed, settings, exit_ip, settings.gpu)
    logger.info(f"Generated machine {pin.get('id')} ({settings.os}, gpu {pinned_gpu(pin)})")
    return pin


def needs_move(pin: dict[str, Any], settings: BrowserSettings, exit_ip: str | None) -> bool:
    """Whether the pin's location group no longer matches the settings and exit."""
    where = pinned_location(pin)
    if settings.languages and where["languages"] != settings.languages:
        return True
    if settings.timezone:
        return where["timezone"] != settings.timezone or (
            exit_ip is not None and where["public_ip"] != exit_ip
        )
    if exit_ip:
        return where["public_ip"] != exit_ip
    return False


def forget_placement(pin: dict[str, Any]) -> dict[str, Any]:
    """The pin without its exit address, so the next launch places it again.

    For when the stated timezone or languages change: the stored location was
    derived from them, and an unchanged exit would otherwise keep it.
    """
    moved = copy.deepcopy(pin)
    ((moved.get("network") or {}).get("webrtc") or {}).pop("public_ip", None)
    return moved


def merge_location(pin: dict[str, Any], fresh: dict[str, Any]) -> dict[str, Any]:
    """The pin with ``fresh``'s location group, and nothing else of it."""
    moved = copy.deepcopy(pin)
    moved["locale"] = copy.deepcopy(fresh["locale"])
    webrtc = moved.setdefault("network", {}).setdefault("webrtc", {})
    public_ip = ((fresh.get("network") or {}).get("webrtc") or {}).get("public_ip")
    if public_ip:
        webrtc["public_ip"] = public_ip
    else:
        webrtc.pop("public_ip", None)
    note = (fresh.get("captured") or {}).get("note")
    if note:
        moved.setdefault("captured", {})["note"] = note
    return moved


async def move(
    pin: dict[str, Any], settings: BrowserSettings, exit_ip: str | None
) -> dict[str, Any]:
    """Move a machine to a new location without touching its hardware."""
    family = pinned_os(pin)
    seed = pin.get("seed")
    if family is None or not isinstance(seed, str):
        raise MachineError("The stored machine has no OS or seed; regenerate it.")
    fresh = await _generate_at(family, seed, settings, exit_ip, pinned_gpu(pin))
    moved = merge_location(pin, fresh)
    before, after = pinned_location(pin), pinned_location(moved)
    logger.info(
        f"Moved machine {pin.get('id')}: {before['public_ip'] or before['timezone']} -> "
        f"{after['public_ip'] or after['timezone']}"
    )
    return moved


@lru_cache(maxsize=4)
def _gpus_for(installation_key: str) -> tuple[dict[str, Any], ...]:
    return tuple(browser_install.run_genprofile("gpus")["gpus"])


def list_gpus(os_family: str | None = None) -> list[dict[str, Any]]:
    """The GPUs a generated machine may claim: captured ones, and those their host class backs."""
    installation = browser_install.current_installation()
    if installation is None:
        return []
    try:
        gpus = _gpus_for(installation.version + str(installation.source))
    except GenprofileError as exc:
        logger.warning(f"Could not list GPUs: {exc}")
        return []
    return [dict(g) for g in gpus if os_family is None or g["os"] == os_family]


def summarize(pin: dict[str, Any] | None, settings_os: str | None = None) -> dict[str, Any] | None:
    """The few values of a pinned machine worth showing a person.

    The stored profile is a few hundred values and tens of kilobytes; this is
    what the UI shows so someone can confirm the profile is a fixed machine.
    """
    if not pin:
        return None
    os_section = pin.get("os") or {}
    hardware = pin.get("hardware") or {}
    display = pin.get("display") or {}
    gpu = pin.get("gpu") or {}
    webgl = gpu.get("webgl") or {}
    fonts = (pin.get("fonts") or {}).get("families")
    where = pinned_location(pin)
    family = pinned_os(pin)
    width, height = display.get("width"), display.get("height")
    installation = browser_install.current_installation()
    return {
        "id": pin.get("id"),
        "seed": pin.get("seed"),
        "os": family,
        "os_version": os_section.get("version"),
        "platform": os_section.get("navigator_platform"),
        "hardware_concurrency": hardware.get("concurrency"),
        "device_memory": hardware.get("device_memory"),
        "screen": f"{width}x{height}" if width and height else None,
        "device_pixel_ratio": display.get("device_pixel_ratio"),
        "gpu": webgl.get("unmasked_renderer") or gpu.get("gl_renderer") or gpu.get("device_name"),
        "gpu_id": pinned_gpu(pin),
        "font_count": len(fonts) if isinstance(fonts, list) else None,
        "timezone": where["timezone"],
        "languages": where["languages"],
        "public_ip": where["public_ip"],
        "has_geolocation": bool(where["geolocation"]),
        # Phasmid reports the version it was built from, so the browser a
        # profile claims is whichever release is installed; nothing to refresh.
        "browser_version": installation.version if installation else None,
        "pinned_os": family,
        "settings_os": settings_os,
        "os_mismatch": bool(family and settings_os and family != settings_os),
    }
