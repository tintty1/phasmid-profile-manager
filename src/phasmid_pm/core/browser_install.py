"""Install a Phasmid release: the browser, its source tree, and the location data.

A launch needs three things:

- the browser, ``phasmid-<tag>-linux-x64.tar.zst`` from the release assets,
  checked against the ``.sha256`` published beside it;
- the source tree at the release tag, for ``tools/proxyroute`` (Chrome cannot
  send proxy credentials on its own);
- the DB-IP City Lite database phasmid-profile-gen places exit addresses with,
  pinned by that package and cached by it under ``$XDG_CACHE_HOME/phasmid/geoip``.

Profiles themselves are generated by the ``phasmid-profile-gen`` package, a
dependency of this one, in a child process (``run_genprofile``).

Everything lands in ``<data dir>/phasmid/<tag>/``; ``current`` names the tag in
use and is written last, so an interrupted install leaves the previous one
working. ``PPM_PHASMID_BINARY`` and ``PPM_PHASMID_SOURCE`` point at a local
build and checkout instead, and then only the location data is downloaded.
"""

from __future__ import annotations

import hashlib
import json
import os
import shutil
import subprocess
import sys
import tarfile
import tempfile
import threading
from collections.abc import Callable
from contextlib import contextmanager
from dataclasses import dataclass
from pathlib import Path
from typing import Any, Literal

import httpx
from phasmid_profile_gen import geoip
from pydantic import BaseModel

from ..config import get_settings

DRIVER = Path(__file__).with_name("genprofile_driver.py")
ASSET = "phasmid-{tag}-linux-x64.tar.zst"


class BrowserStatus(BaseModel):
    installed: bool
    version: str | None = None
    state: Literal["idle", "downloading", "ready", "error"] = "idle"
    progress: int | None = None
    message: str = "Download the browser to open your first profile."
    error: str | None = None


class GenprofileError(RuntimeError):
    """phasmid-profile-gen refused or failed; the message is its own."""


@dataclass(frozen=True)
class Installation:
    """One usable Phasmid: the binary, and the source tree of the same release (for proxyroute)."""

    version: str
    binary: Path
    source: Path

    @property
    def proxyroute(self) -> Path:
        return self.source / "tools" / "proxyroute" / "proxyroute.py"


def install_root() -> Path:
    return Path(get_settings().db_path).expanduser().resolve().parent / "phasmid"


def usable_source(path: Path) -> bool:
    return (path / "tools" / "proxyroute" / "proxyroute.py").is_file()


def _configured() -> Installation | None:
    """A local build and/or checkout named in the settings.

    Either one alone is completed from the downloaded release, so a developer
    can try a new build against the released proxyroute or the other way round.
    """
    settings = get_settings()
    if not settings.phasmid_binary and not settings.phasmid_source:
        return None
    current = _downloaded(install_root())
    binary = Path(settings.phasmid_binary).expanduser() if settings.phasmid_binary else None
    source = Path(settings.phasmid_source).expanduser() if settings.phasmid_source else None
    binary = binary or (current.binary if current else None)
    source = source or (current.source if current else None)
    if binary is None or source is None:
        return None
    try:
        version = (source / "chromium_version.txt").read_text().strip()
    except OSError:
        version = "unknown"
    return Installation(f"{version} (local)", binary, source)


def _downloaded(root: Path) -> Installation | None:
    try:
        tag = (root / "current").read_text().strip()
    except OSError:
        return None
    if not tag or "/" in tag or tag.startswith("."):
        return None
    base = root / tag
    return Installation(tag, base / "browser" / "chrome", base / "source")


def current_installation() -> Installation | None:
    """The installation launches use, whether or not it is complete."""
    return _configured() or _downloaded(install_root())


def geoip_ready() -> bool:
    """Whether the location database phasmid-profile-gen reads is on disk.

    That is ``$PHASMID_GEOIP_MMDB`` when set, else the build the package pins.
    """
    chosen = os.environ.get(geoip.ENV_MMDB)
    if chosen:
        return Path(chosen).expanduser().is_file()
    return geoip.cached_path().is_file()


def installed_browser() -> tuple[bool, str | None]:
    """Whether a launch can start right now, and the release it would use."""
    installation = current_installation()
    if installation is None:
        return False, None
    ok = (
        installation.binary.is_file()
        and os.access(installation.binary, os.X_OK)
        and usable_source(installation.source)
        and installation.proxyroute.is_file()
        and geoip_ready()
    )
    return ok, installation.version


def require_installation() -> Installation:
    from .browser_session import BrowserLaunchError

    installation = current_installation()
    if installation is None or not installed_browser()[0]:
        raise BrowserLaunchError(
            "The browser needs setup. Open Settings and click Install browser before launching a profile."
        )
    return installation


def ensure_browser_ready() -> None:
    require_installation()


def run_genprofile(command: str, args: dict[str, Any] | None = None) -> dict[str, Any]:
    """Run one phasmid-profile-gen command (see genprofile_driver.py) and return its answer.

    Blocking: call it from a worker thread.
    """
    argv = [sys.executable, str(DRIVER), command, json.dumps(args or {})]
    try:
        completed = subprocess.run(
            argv,
            capture_output=True,
            text=True,
            timeout=900 if command == "geoip" else 120,
            check=False,
        )
    except subprocess.TimeoutExpired as exc:
        raise GenprofileError(f"genprofile {command} took too long") from exc
    try:
        answer = json.loads(completed.stdout.strip().splitlines()[-1])
    except (IndexError, ValueError) as exc:
        tail = completed.stderr.strip()[-500:] or "no output"
        raise GenprofileError(f"genprofile {command} failed: {tail}") from exc
    if "error" in answer:
        raise GenprofileError(answer["error"])
    return answer


@contextmanager
def installation_lock():
    """Serialize downloads across manager processes, released on process exit."""
    import fcntl

    root = install_root()
    root.mkdir(parents=True, exist_ok=True)
    with (root / ".install.lock").open("a+b") as handle:
        try:
            fcntl.flock(handle.fileno(), fcntl.LOCK_EX | fcntl.LOCK_NB)
        except OSError as exc:
            raise RuntimeError(
                "Another application is installing Phasmid. Try again later."
            ) from exc
        try:
            yield
        finally:
            fcntl.flock(handle.fileno(), fcntl.LOCK_UN)


def find_release(client: httpx.Client, repo: str, tag: str | None) -> dict[str, Any]:
    """The release to install: ``tag``, or the newest one that has a Linux build.

    Pre-releases count: Phasmid has shipped nothing else yet.
    """
    headers = {"Accept": "application/vnd.github+json"}
    if tag:
        url = f"https://api.github.com/repos/{repo}/releases/tags/{tag}"
        response = client.get(url, headers=headers)
        response.raise_for_status()
        releases = [response.json()]
    else:
        response = client.get(f"https://api.github.com/repos/{repo}/releases", headers=headers)
        response.raise_for_status()
        releases = response.json()
    for release in releases:
        if release.get("draft"):
            continue
        names = {asset["name"] for asset in release.get("assets", [])}
        wanted = ASSET.format(tag=release["tag_name"])
        if wanted in names and f"{wanted}.sha256" in names:
            return release
    where = f" at {tag}" if tag else ""
    raise RuntimeError(f"No release of {repo} has a Linux x64 build{where}")


def _asset_url(release: dict[str, Any], name: str) -> str:
    for asset in release["assets"]:
        if asset["name"] == name:
            return asset["browser_download_url"]
    raise RuntimeError(f"Release {release['tag_name']} has no {name}")


def _download(
    client: httpx.Client,
    url: str,
    dest: Path,
    progress: Callable[[int, int], None] | None = None,
) -> str:
    """Stream ``url`` into ``dest``; returns the SHA-256 of what was written."""
    digest = hashlib.sha256()
    with client.stream("GET", url, follow_redirects=True, timeout=60) as response:
        response.raise_for_status()
        total = int(response.headers.get("content-length", 0))
        count = 0
        with dest.open("wb") as handle:
            for chunk in response.iter_bytes(1 << 20):
                handle.write(chunk)
                digest.update(chunk)
                count += len(chunk)
                if progress is not None:
                    progress(count, total)
    return digest.hexdigest()


def _extract_single_root(archive: tarfile.TarFile, dest: Path) -> None:
    """Extract an archive whose members all sit under one top directory into ``dest``.

    The ``data`` filter refuses absolute paths, ``..``, device files and links
    leaving the archive, so a tampered archive cannot write outside ``dest``.
    """
    dest.parent.mkdir(parents=True, exist_ok=True)
    staging = Path(tempfile.mkdtemp(dir=dest.parent, prefix=f".{dest.name}-"))
    try:
        archive.extractall(staging, filter="data")
        entries = list(staging.iterdir())
        if len(entries) != 1 or not entries[0].is_dir():
            raise RuntimeError("Unexpected archive layout: expected one top-level directory")
        if dest.exists():
            shutil.rmtree(dest)
        entries[0].rename(dest)
    finally:
        shutil.rmtree(staging, ignore_errors=True)


def extract_zst(path: Path, dest: Path) -> None:
    import zstandard

    with path.open("rb") as raw:
        reader = zstandard.ZstdDecompressor().stream_reader(raw)
        with tarfile.open(fileobj=reader, mode="r|") as archive:
            _extract_single_root(archive, dest)


def extract_gz(path: Path, dest: Path) -> None:
    with tarfile.open(path, mode="r:gz") as archive:
        _extract_single_root(archive, dest)


def _write_current(root: Path, tag: str) -> None:
    temp = root / ".current.tmp"
    temp.write_text(tag + "\n")
    temp.replace(root / "current")


class BrowserInstaller:
    def __init__(self) -> None:
        self._lock = threading.Lock()
        self._state = BrowserStatus(installed=False)
        self._thread: threading.Thread | None = None

    def status(self) -> BrowserStatus:
        installed, version = installed_browser()
        with self._lock:
            result = self._state.model_copy(update={"installed": installed, "version": version})
        if result.state not in ("downloading", "error"):
            result.state = "ready" if installed else "idle"
            result.message = (
                "Browser is ready."
                if installed
                else "Download the browser to open your first profile."
            )
        return result

    def _update(self, **values: Any) -> None:
        with self._lock:
            self._state = self._state.model_copy(update=values)

    def start(self) -> BrowserStatus:
        with self._lock:
            if self._state.state != "downloading":
                self._state = BrowserStatus(
                    installed=False,
                    state="downloading",
                    progress=None,
                    message="Finding a Phasmid release…",
                )
                self._thread = threading.Thread(
                    target=self._run, daemon=True, name="browser-download"
                )
                self._thread.start()
        return self.status()

    def _run(self) -> None:
        try:
            with installation_lock():
                self._install()
            installed, version = installed_browser()
            if not installed:
                raise RuntimeError(
                    "The install finished but required files are missing. Try again."
                )
            self._update(
                installed=True,
                version=version,
                state="ready",
                progress=100,
                message="Browser is ready.",
                error=None,
            )
        except Exception as exc:  # noqa: BLE001 - shown to the user with a retry
            self._update(
                state="error",
                progress=None,
                message="Could not finish installing the browser. Check your connection and retry.",
                error=str(exc),
            )

    def _install(self) -> None:
        settings = get_settings()
        configured = _configured()
        if (
            configured is not None
            and configured.binary.is_file()
            and usable_source(configured.source)
        ):
            # A local build: only the location data can be missing.
            self._fetch_geoip()
            return

        root = install_root()
        with httpx.Client(timeout=30) as client:
            release = find_release(client, settings.phasmid_repo, settings.phasmid_release)
            tag = release["tag_name"]
            base = root / tag
            base.mkdir(parents=True, exist_ok=True)
            installation = Installation(tag, base / "browser" / "chrome", base / "source")

            if not installation.binary.is_file():
                name = ASSET.format(tag=tag)
                checksum = client.get(_asset_url(release, f"{name}.sha256"), follow_redirects=True)
                checksum.raise_for_status()
                expected = checksum.text.split()[0].lower()
                with tempfile.TemporaryDirectory(dir=base, prefix=".download-") as tmp:
                    archive = Path(tmp) / name

                    def progress(count: int, total: int) -> None:
                        self._update(
                            progress=min(80, int(count / total * 80)) if total else None,
                            message=f"Downloading Phasmid {tag}…",
                        )

                    actual = _download(client, _asset_url(release, name), archive, progress)
                    if actual != expected:
                        raise RuntimeError("Browser download checksum did not match. Please retry.")
                    self._update(progress=81, message="Unpacking the browser…")
                    extract_zst(archive, base / "browser")

            if not usable_source(installation.source):
                self._update(progress=85, message="Downloading the proxy relay…")
                with tempfile.TemporaryDirectory(dir=base, prefix=".download-") as tmp:
                    archive = Path(tmp) / "source.tar.gz"
                    _download(
                        client,
                        f"https://github.com/{settings.phasmid_repo}/archive/refs/tags/{tag}.tar.gz",
                        archive,
                    )
                    extract_gz(archive, installation.source)

        self._fetch_geoip()
        _write_current(root, tag)

    def _fetch_geoip(self) -> None:
        if geoip_ready():
            return
        self._update(progress=90, message="Downloading the location database (about 60 MB)…")
        run_genprofile("geoip")


browser_installer = BrowserInstaller()
