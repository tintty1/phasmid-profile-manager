"""Install a Phasmid release: the browser, its source tree, and the location data.

A launch needs three things:

- the browser, ``phasmid-<tag>-linux-x64.tar.zst`` from the release assets,
  checked against the ``.sha256`` published beside it;
- the source tree at the release tag, for ``tools/proxyroute`` (Chrome cannot
  send proxy credentials on its own);
- the DB-IP City Lite database phasmid-profile-gen places exit addresses with,
  pinned by that package and cached by it under ``$XDG_CACHE_HOME/phasmid/geoip``.

Profiles themselves are generated by the ``phasmid-profile-gen`` package, a
dependency of this one, in a child process (``run_genprofile``).

Everything lands in ``<data dir>/phasmid/<tag>/``, one directory per release,
side by side. ``current`` names the newest one installed: the release a profile
without a pinned version launches with. It is written last, so an interrupted
install leaves the previous one working. A profile that pins a release
(``BrowserSettings.phasmid_version``) launches with that directory instead.

Once a release is installed, every start of the API checks for a newer one and
installs it in the background (``update_on_start``), along with any release a
profile pins that is not on disk yet. ``PPM_PHASMID_AUTO_UPDATE=false`` turns
that off. ``PPM_PHASMID_BINARY`` and ``PPM_PHASMID_SOURCE`` point at a local
build and checkout instead of ``current``, and then only the location data and
pinned releases are downloaded.
"""

from __future__ import annotations

import hashlib
import json
import os
import re
import shutil
import subprocess
import sys
import tarfile
import tempfile
import threading
from collections.abc import Callable, Iterable
from contextlib import contextmanager
from dataclasses import dataclass
from pathlib import Path
from typing import Any, Literal

import httpx
from loguru import logger
from phasmid_profile_gen import geoip
from pydantic import BaseModel

from ..config import get_settings

DRIVER = Path(__file__).with_name("genprofile_driver.py")
ASSET = "phasmid-{tag}-linux-x64.tar.zst"
# A release tag as Phasmid names them (155.0.8059.84-p1). Also what keeps a tag
# from a profile or the ``current`` file from naming a path outside the root.
TAG = re.compile(r"^[0-9A-Za-z][0-9A-Za-z._+-]{0,63}$")


def valid_tag(tag: str | None) -> bool:
    return tag is not None and TAG.match(tag) is not None and ".." not in tag


class BrowserStatus(BaseModel):
    installed: bool
    version: str | None = None
    # Every complete release on disk, newest first: what a profile can be pinned
    # to without waiting for a download.
    versions: list[str] = []
    state: Literal["idle", "downloading", "ready", "error"] = "idle"
    progress: int | None = None
    message: str = "Download the browser to open your first profile."
    error: str | None = None


class GenprofileError(RuntimeError):
    """phasmid-profile-gen refused or failed; the message is its own."""


@dataclass(frozen=True)
class Installation:
    """One usable Phasmid: the binary, and the source tree of the same release (for proxyroute)."""

    version: str
    binary: Path
    source: Path

    @property
    def proxyroute(self) -> Path:
        return self.source / "tools" / "proxyroute" / "proxyroute.py"


def install_root() -> Path:
    return Path(get_settings().db_path).expanduser().resolve().parent / "phasmid"


def usable_source(path: Path) -> bool:
    return (path / "tools" / "proxyroute" / "proxyroute.py").is_file()


def _configured() -> Installation | None:
    """A local build and/or checkout named in the settings.

    Either one alone is completed from the downloaded release, so a developer
    can try a new build against the released proxyroute or the other way round.
    """
    settings = get_settings()
    if not settings.phasmid_binary and not settings.phasmid_source:
        return None
    current = _downloaded(install_root())
    binary = Path(settings.phasmid_binary).expanduser() if settings.phasmid_binary else None
    source = Path(settings.phasmid_source).expanduser() if settings.phasmid_source else None
    binary = binary or (current.binary if current else None)
    source = source or (current.source if current else None)
    if binary is None or source is None:
        return None
    try:
        version = (source / "chromium_version.txt").read_text().strip()
    except OSError:
        version = "unknown"
    return Installation(f"{version} (local)", binary, source)


def _downloaded(root: Path, tag: str | None = None) -> Installation | None:
    """The release ``tag`` under ``root``, or the one ``current`` names."""
    if tag is None:
        try:
            tag = (root / "current").read_text().strip()
        except OSError:
            return None
    if not valid_tag(tag):
        return None
    base = root / tag
    return Installation(tag, base / "browser" / "chrome", base / "source")


def current_installation() -> Installation | None:
    """The installation unpinned profiles launch with, whether or not it is complete."""
    return _configured() or _downloaded(install_root())


def installation_for(version: str | None) -> Installation | None:
    """The installation a profile pinned to ``version`` (None: not pinned) launches with."""
    if version:
        return _downloaded(install_root(), version)
    return current_installation()


def _complete(installation: Installation | None) -> bool:
    return (
        installation is not None
        and installation.binary.is_file()
        and os.access(installation.binary, os.X_OK)
        and usable_source(installation.source)
        and installation.proxyroute.is_file()
    )


def version_key(tag: str) -> tuple[int, ...]:
    """Orders 156.0.8078.79-p1 after 155.0.8059.84-p2 after 155.0.8059.84-p1."""
    return tuple(int(part) for part in re.findall(r"\d+", tag))


def installed_versions() -> list[str]:
    """Every complete downloaded release, newest first."""
    root = install_root()
    try:
        names = [entry.name for entry in root.iterdir() if entry.is_dir()]
    except OSError:
        return []
    found = [name for name in names if valid_tag(name) and _complete(_downloaded(root, name))]
    return sorted(found, key=version_key, reverse=True)


def geoip_ready() -> bool:
    """Whether the location database phasmid-profile-gen reads is on disk.

    That is ``$PHASMID_GEOIP_MMDB`` when set, else the build the package pins.
    """
    chosen = os.environ.get(geoip.ENV_MMDB)
    if chosen:
        return Path(chosen).expanduser().is_file()
    return geoip.cached_path().is_file()


def installed_browser(version: str | None = None) -> tuple[bool, str | None]:
    """Whether a launch can start right now, and the release it would use.

    ``version`` is a profile's pinned release; None asks about ``current``.
    """
    installation = installation_for(version)
    if installation is None:
        return False, None
    return _complete(installation) and geoip_ready(), installation.version


def require_installation(version: str | None = None) -> Installation:
    """The installation to launch a profile pinned to ``version`` with, or why not.

    A pinned release that is not on disk yet starts downloading, so launching
    again once it is done works without a trip to Settings.
    """
    from .browser_session import BrowserLaunchError

    installation = installation_for(version)
    if installation is not None and installed_browser(version)[0]:
        return installation
    if version and current_installation() is not None:
        browser_installer.start(version)
        raise BrowserLaunchError(
            f"This profile uses Phasmid {version}, which is not installed yet. It is "
            "downloading now (Settings shows progress); launch again when it is done."
        )
    raise BrowserLaunchError(
        "The browser needs setup. Open Settings and click Install browser before launching a profile."
    )


def ensure_browser_ready() -> None:
    require_installation()


def run_genprofile(command: str, args: dict[str, Any] | None = None) -> dict[str, Any]:
    """Run one phasmid-profile-gen command (see genprofile_driver.py) and return its answer.

    Blocking: call it from a worker thread.
    """
    argv = [sys.executable, str(DRIVER), command, json.dumps(args or {})]
    try:
        completed = subprocess.run(
            argv,
            capture_output=True,
            text=True,
            timeout=900 if command == "geoip" else 120,
            check=False,
        )
    except subprocess.TimeoutExpired as exc:
        raise GenprofileError(f"genprofile {command} took too long") from exc
    try:
        answer = json.loads(completed.stdout.strip().splitlines()[-1])
    except (IndexError, ValueError) as exc:
        tail = completed.stderr.strip()[-500:] or "no output"
        raise GenprofileError(f"genprofile {command} failed: {tail}") from exc
    if "error" in answer:
        raise GenprofileError(answer["error"])
    return answer


@contextmanager
def installation_lock():
    """Serialize downloads across manager processes, released on process exit."""
    import fcntl

    root = install_root()
    root.mkdir(parents=True, exist_ok=True)
    with (root / ".install.lock").open("a+b") as handle:
        try:
            fcntl.flock(handle.fileno(), fcntl.LOCK_EX | fcntl.LOCK_NB)
        except OSError as exc:
            raise RuntimeError(
                "Another application is installing Phasmid. Try again later."
            ) from exc
        try:
            yield
        finally:
            fcntl.flock(handle.fileno(), fcntl.LOCK_UN)


def find_release(client: httpx.Client, repo: str, tag: str | None) -> dict[str, Any]:
    """The release to install: ``tag``, or the newest one that has a Linux build.

    Pre-releases count: Phasmid has shipped nothing else yet.
    """
    headers = {"Accept": "application/vnd.github+json"}
    if tag:
        url = f"https://api.github.com/repos/{repo}/releases/tags/{tag}"
        response = client.get(url, headers=headers)
        response.raise_for_status()
        releases = [response.json()]
    else:
        response = client.get(f"https://api.github.com/repos/{repo}/releases", headers=headers)
        response.raise_for_status()
        releases = response.json()
    for release in releases:
        if release.get("draft"):
            continue
        if _has_linux_build(release):
            return release
    where = f" at {tag}" if tag else ""
    raise RuntimeError(f"No release of {repo} has a Linux x64 build{where}")


def _has_linux_build(release: dict[str, Any]) -> bool:
    names = {asset["name"] for asset in release.get("assets", [])}
    wanted = ASSET.format(tag=release["tag_name"])
    return wanted in names and f"{wanted}.sha256" in names


class PhasmidReleases(BaseModel):
    """What can be installed: every published release with a Linux build, newest first."""

    current: str | None = None
    latest: str | None = None
    update_available: bool = False
    releases: list[str] = []
    installed: list[str] = []
    error: str | None = None


def available_releases() -> PhasmidReleases:
    """Releases of ``phasmid_repo`` a profile can pin or the manager can update to."""
    settings = get_settings()
    installed = installed_versions()
    current = current_installation()
    current_tag = current.version if current and _complete(current) else None
    try:
        with httpx.Client(timeout=15) as client:
            response = client.get(
                f"https://api.github.com/repos/{settings.phasmid_repo}/releases",
                headers={"Accept": "application/vnd.github+json"},
            )
            response.raise_for_status()
            published = response.json()
    except (httpx.HTTPError, ValueError) as exc:
        logger.warning(f"Could not list Phasmid releases: {exc}")
        return PhasmidReleases(
            current=current_tag,
            installed=installed,
            error="Could not reach GitHub to list Phasmid releases.",
        )
    tags = [
        release["tag_name"]
        for release in published
        if not release.get("draft")
        and valid_tag(release.get("tag_name"))
        and _has_linux_build(release)
    ]
    tags = sorted(set(tags), key=version_key, reverse=True)
    latest = tags[0] if tags else None
    return PhasmidReleases(
        current=current_tag,
        latest=latest,
        update_available=bool(
            latest
            and current_tag
            and valid_tag(current_tag)
            and version_key(latest) > version_key(current_tag)
        ),
        releases=tags,
        installed=installed,
    )


class BrowserVersion(BaseModel):
    """One Phasmid release a profile can pin (``browser_settings.phasmid_version``)."""

    version: str
    # Complete on disk: a profile pinned to it launches without waiting.
    installed: bool
    # Published on GitHub with a Linux build: pinning it downloads it if missing.
    published: bool
    # The global release: what profiles without a pin launch with.
    is_global: bool
    is_latest: bool


class BrowserVersions(BaseModel):
    global_version: str | None = None
    latest: str | None = None
    versions: list[BrowserVersion] = []
    # Set when GitHub could not be reached: ``versions`` then lists only what is installed.
    error: str | None = None


def browser_versions() -> BrowserVersions:
    """Every version a profile can be pinned to, installed or published, newest first."""
    found = available_releases()
    published = set(found.releases)
    installed = set(found.installed)
    tags = sorted(published | installed, key=version_key, reverse=True)
    return BrowserVersions(
        global_version=found.current,
        latest=found.latest,
        versions=[
            BrowserVersion(
                version=tag,
                installed=tag in installed,
                published=tag in published,
                is_global=tag == found.current,
                is_latest=tag == found.latest,
            )
            for tag in tags
        ],
        error=found.error,
    )


def _asset_url(release: dict[str, Any], name: str) -> str:
    for asset in release["assets"]:
        if asset["name"] == name:
            return asset["browser_download_url"]
    raise RuntimeError(f"Release {release['tag_name']} has no {name}")


def _download(
    client: httpx.Client,
    url: str,
    dest: Path,
    progress: Callable[[int, int], None] | None = None,
) -> str:
    """Stream ``url`` into ``dest``; returns the SHA-256 of what was written."""
    digest = hashlib.sha256()
    with client.stream("GET", url, follow_redirects=True, timeout=60) as response:
        response.raise_for_status()
        total = int(response.headers.get("content-length", 0))
        count = 0
        with dest.open("wb") as handle:
            for chunk in response.iter_bytes(1 << 20):
                handle.write(chunk)
                digest.update(chunk)
                count += len(chunk)
                if progress is not None:
                    progress(count, total)
    return digest.hexdigest()


def _extract_single_root(archive: tarfile.TarFile, dest: Path) -> None:
    """Extract an archive whose members all sit under one top directory into ``dest``.

    The ``data`` filter refuses absolute paths, ``..``, device files and links
    leaving the archive, so a tampered archive cannot write outside ``dest``.
    """
    dest.parent.mkdir(parents=True, exist_ok=True)
    staging = Path(tempfile.mkdtemp(dir=dest.parent, prefix=f".{dest.name}-"))
    try:
        archive.extractall(staging, filter="data")
        entries = list(staging.iterdir())
        if len(entries) != 1 or not entries[0].is_dir():
            raise RuntimeError("Unexpected archive layout: expected one top-level directory")
        if dest.exists():
            shutil.rmtree(dest)
        entries[0].rename(dest)
    finally:
        shutil.rmtree(staging, ignore_errors=True)


def extract_zst(path: Path, dest: Path) -> None:
    import zstandard

    with path.open("rb") as raw:
        reader = zstandard.ZstdDecompressor().stream_reader(raw)
        with tarfile.open(fileobj=reader, mode="r|") as archive:
            _extract_single_root(archive, dest)


def extract_gz(path: Path, dest: Path) -> None:
    with tarfile.open(path, mode="r:gz") as archive:
        _extract_single_root(archive, dest)


def _write_current(root: Path, tag: str) -> None:
    temp = root / ".current.tmp"
    temp.write_text(tag + "\n")
    temp.replace(root / "current")


class BrowserInstaller:
    """Installs releases one after another on a background thread.

    Each queued item is a tag, or None for the newest release (which becomes
    ``current``). A background item is an update nobody asked for: when it
    fails, the releases already on disk keep working, so the failure is logged
    rather than shown as an install error.
    """

    def __init__(self) -> None:
        self._lock = threading.Lock()
        self._state = BrowserStatus(installed=False)
        self._thread: threading.Thread | None = None
        self._queue: list[tuple[str | None, bool]] = []
        self._errors: list[str] = []

    def status(self) -> BrowserStatus:
        installed, version = installed_browser()
        with self._lock:
            result = self._state.model_copy(
                update={
                    "installed": installed,
                    "version": version,
                    "versions": installed_versions(),
                }
            )
        if result.state not in ("downloading", "error"):
            result.state = "ready" if installed else "idle"
            result.message = (
                "Browser is ready."
                if installed
                else "Download the browser to open your first profile."
            )
        return result

    def _update(self, **values: Any) -> None:
        with self._lock:
            self._state = self._state.model_copy(update=values)

    def start(self, version: str | None = None, background: bool = False) -> BrowserStatus:
        """Queue ``version`` (None: the newest release) and start installing if idle."""
        if version is not None and not valid_tag(version):
            raise ValueError(f"{version!r} is not a Phasmid release tag")
        with self._lock:
            queued = [tag for tag, _ in self._queue]
            if version not in queued:
                self._queue.append((version, background))
            elif not background:
                # Asked for by a person now: report its failure after all.
                self._queue = [(tag, quiet and tag != version) for tag, quiet in self._queue]
            if self._state.state != "downloading":
                self._errors = []
                self._state = BrowserStatus(
                    installed=False,
                    state="downloading",
                    progress=None,
                    message="Finding a Phasmid release…",
                )
                self._thread = threading.Thread(
                    target=self._run, daemon=True, name="browser-download"
                )
                self._thread.start()
        return self.status()

    def _run(self) -> None:
        while True:
            with self._lock:
                if not self._queue:
                    # Decided under the lock, so a start() that queues something
                    # now either lands before this (and is run) or sees the job
                    # finished and starts a new one.
                    self._finish()
                    return
                version, background = self._queue.pop(0)
            try:
                with installation_lock():
                    self._install(version)
                if not installed_browser(version)[0]:
                    raise RuntimeError(
                        "The install finished but required files are missing. Try again."
                    )
            except Exception as exc:  # noqa: BLE001 - shown to the user with a retry
                name = f"Phasmid {version}" if version else "the newest Phasmid release"
                if background:
                    logger.warning(f"Could not install {name}: {exc}")
                else:
                    with self._lock:
                        self._errors.append(f"{name}: {exc}" if version else str(exc))

    def _finish(self) -> None:
        """Set the outcome of the whole job. Call with the lock held."""
        if self._errors:
            self._state = self._state.model_copy(
                update={
                    "state": "error",
                    "progress": None,
                    "message": "Could not finish installing the browser. Check your connection and retry.",
                    "error": "; ".join(self._errors),
                }
            )
        else:
            self._state = self._state.model_copy(
                update={
                    "state": "ready",
                    "progress": 100,
                    "message": "Browser is ready.",
                    "error": None,
                }
            )

    def _install(self, version: str | None = None) -> None:
        settings = get_settings()
        configured = _configured()
        if (
            version is None
            and configured is not None
            and configured.binary.is_file()
            and usable_source(configured.source)
        ):
            # A local build: only the location data can be missing.
            self._fetch_geoip()
            return

        root = install_root()
        if version is not None and _complete(_downloaded(root, version)):
            self._fetch_geoip()
            return
        with httpx.Client(timeout=30) as client:
            release = find_release(
                client, settings.phasmid_repo, version or settings.phasmid_release
            )
            tag = release["tag_name"]
            if not valid_tag(tag):
                raise RuntimeError(f"Release tag {tag!r} cannot name a directory")
            base = root / tag
            base.mkdir(parents=True, exist_ok=True)
            installation = Installation(tag, base / "browser" / "chrome", base / "source")

            if not installation.binary.is_file():
                name = ASSET.format(tag=tag)
                checksum = client.get(_asset_url(release, f"{name}.sha256"), follow_redirects=True)
                checksum.raise_for_status()
                expected = checksum.text.split()[0].lower()
                with tempfile.TemporaryDirectory(dir=base, prefix=".download-") as tmp:
                    archive = Path(tmp) / name

                    def progress(count: int, total: int) -> None:
                        self._update(
                            progress=min(80, int(count / total * 80)) if total else None,
                            message=f"Downloading Phasmid {tag}…",
                        )

                    actual = _download(client, _asset_url(release, name), archive, progress)
                    if actual != expected:
                        raise RuntimeError("Browser download checksum did not match. Please retry.")
                    self._update(progress=81, message="Unpacking the browser…")
                    extract_zst(archive, base / "browser")

            if not usable_source(installation.source):
                self._update(progress=85, message="Downloading the proxy relay…")
                with tempfile.TemporaryDirectory(dir=base, prefix=".download-") as tmp:
                    archive = Path(tmp) / "source.tar.gz"
                    _download(
                        client,
                        f"https://github.com/{settings.phasmid_repo}/archive/refs/tags/{tag}.tar.gz",
                        archive,
                    )
                    extract_gz(archive, installation.source)

        self._fetch_geoip()
        if version is None:
            _write_current(root, tag)

    def _fetch_geoip(self) -> None:
        if geoip_ready():
            return
        self._update(progress=90, message="Downloading the location database (about 60 MB)…")
        run_genprofile("geoip")


browser_installer = BrowserInstaller()


def update_on_start(pinned: Iterable[str]) -> None:
    """Install the newest release, and every pinned one missing, in the background.

    Only once a release is installed: the first download is several hundred
    megabytes and stays something a person starts (Settings > Install browser).
    Profiles without a pinned version launch with the new release from their
    next launch; a browser already open keeps running the one it started with.
    """
    settings = get_settings()
    if not settings.phasmid_auto_update or current_installation() is None:
        return
    browser_installer.start(None, background=True)
    for version in sorted(set(pinned), key=version_key):
        if valid_tag(version) and not installed_browser(version)[0]:
            browser_installer.start(version, background=True)
